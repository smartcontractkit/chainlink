package v2

import (
	"context"
	"time"

	"github.com/smartcontractkit/chainlink-common/pkg/workflows/wasm/workflowLib"
)

type TimeProvider struct {
	workflowExecutionID string
	timeSeqNum          int
	donTimeStore        *workflowLib.DonTimeStore
}

func NewTimeProvider(workflowExecutionID string) TimeProvider {
	return TimeProvider{
		workflowExecutionID: workflowExecutionID,
		timeSeqNum:          0,
		donTimeStore:        workflowLib.GetDonTimeStore(),
	}
}

func (tp *TimeProvider) GetNodeTime() time.Time {
	return fromUnixMilli(tp.donTimeStore.GetLastObservedDonTime())
}

// GetDONTime makes a request to the WorkflowLib plugin store for DON Time
func (tp *TimeProvider) GetDONTime(ctx context.Context) (time.Time, error) {
	defer func() {
		tp.timeSeqNum++
	}()

	select {
	case donTimeResp := <-tp.donTimeStore.RequestDonTime(tp.workflowExecutionID, tp.timeSeqNum):
		if donTimeResp.Err != nil {
			// This node's request timed out, so it did not include the request in its observation.
			// However, consensus may still have been reached if other nodes included the request.
			if donTime := tp.donTimeStore.GetDonTimeForSeqNum(tp.workflowExecutionID, tp.timeSeqNum); donTime != nil {
				// Consensus was reached; return the DON time generated by the network.
				return fromUnixMilli(*donTime), nil
			}
			// No DON time was reached yet, so return local node time as a fallback.
			// This may lead to non-determinism across nodes for this workflow step.
			return tp.GetNodeTime(), nil
		}
		return fromUnixMilli(donTimeResp.Timestamp), nil
	case <-ctx.Done():
		return time.Time{}, ctx.Err()
	}
}

func fromUnixMilli(ms int64) time.Time {
	return time.Unix(0, ms*int64(time.Millisecond)).UTC()
}
