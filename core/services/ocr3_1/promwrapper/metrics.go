// Package promwrapper instruments an OCR3.1 ReportingPlugin with prometheus
// metrics. It is the OCR3.1 counterpart of core/services/ocr3/promwrapper and
// mirrors that package's structure (see also the ocr3 / ocr3_1 split of
// beholderwrapper).
//
// Metrics are emitted under their own ocr3_1_reporting_plugin_* names (distinct
// from the OCR3.0 wrapper's ocr3_reporting_plugin_* series) so the two protocol
// versions are independently observable and so the two packages never contend
// for the same collector registration.
package promwrapper

import (
	"time"

	"github.com/prometheus/client_golang/prometheus"
	"github.com/prometheus/client_golang/prometheus/promauto"
)

type functionType string

const (
	query               functionType = "query"
	observation         functionType = "observation"
	validateObservation functionType = "validateObservation"
	observationQuorum   functionType = "observationQuorum"
	stateTransition     functionType = "stateTransition"
	committed           functionType = "committed"
	reports             functionType = "reports"
	shouldAccept        functionType = "shouldAccept"
	shouldTransmit      functionType = "shouldTransmit"
)

var (
	buckets = []float64{
		float64(10 * time.Millisecond),
		float64(50 * time.Millisecond),
		float64(100 * time.Millisecond),
		float64(200 * time.Millisecond),
		float64(500 * time.Millisecond),
		float64(700 * time.Millisecond),
		float64(time.Second),
		float64(2 * time.Second),
		float64(5 * time.Second),
		float64(10 * time.Second),
		float64(20 * time.Second),
		float64(30 * time.Second),
	}

	promOCR3ReportsGenerated = promauto.NewCounterVec(
		prometheus.CounterOpts{
			Name: "ocr3_1_reporting_plugin_reports_processed",
			Help: "Tracks number of reports processed/generated by different OCR3.1 functions",
		},
		[]string{"chainFamily", "chainID", "plugin", "function"},
	)
	promOCR3Durations = promauto.NewHistogramVec(
		prometheus.HistogramOpts{
			Name:    "ocr3_1_reporting_plugin_duration",
			Help:    "The amount of time elapsed during the OCR3.1 plugin's function",
			Buckets: buckets,
		},
		[]string{"chainFamily", "chainID", "plugin", "function", "success"},
	)
	promOCR3Sizes = promauto.NewCounterVec(
		prometheus.CounterOpts{
			Name: "ocr3_1_reporting_plugin_data_sizes",
			Help: "Tracks the size of the data produced by the OCR3.1 plugin in bytes (e.g. reports, observations etc.)",
		},
		[]string{"chainFamily", "chainID", "plugin", "function"},
	)
	promOCR3PluginStatus = promauto.NewGaugeVec(
		prometheus.GaugeOpts{
			Name: "ocr3_1_reporting_plugin_status",
			Help: "Gauge indicating whether the OCR3.1 plugin is up and running or not",
		},
		[]string{"chainFamily", "chainID", "plugin", "configDigest"},
	)
)

func boolToInt(arg bool) int {
	if arg {
		return 1
	}
	return 0
}
