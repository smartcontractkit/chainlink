// IsBinary checks whether the byte slice contains a NUL byte within the first 8KB.
func IsBinary(data []byte) bool {
	checkLen := min(len(data), maxBinaryCheckBytes)
	return bytes.IndexByte(data[:checkLen], 0) != -1
}

// IsEligiblePath performs a zero-IO check on path and extension.
func IsEligiblePath(relPath string) bool {
	clean := filepath.ToSlash(filepath.Clean(relPath))
	clean = strings.TrimPrefix(clean, "./")

	// Skip git internal and build artifact directories.
	// core/web/assets is generated operator UI output (regenerated by
	// make generate); formatting "fixes" there drift from CI output.
	if strings.HasPrefix(clean, ".git/") || clean == ".git" ||
		strings.HasPrefix(clean, ".bin/") || clean == ".bin" ||
		strings.Contains(clean, "/.bin/") ||
		strings.HasPrefix(clean, "core/web/assets/") ||
		strings.HasPrefix(clean, "vendor/") ||
		strings.Contains(clean, "/vendor/") {
		return false
	}

	base := strings.ToLower(filepath.Base(clean))
	ext := strings.ToLower(filepath.Ext(clean))

	// Check binary extension blocklist
	if binaryExtensions[ext] {
		return false
	}

	// Check eligible extension / filename allowlist
	return eligibleExtensions[ext] || eligibleExactFilenames[base]
}

// IsEligible checks if a path and its initial content belong to an eligible text/code file.
func IsEligible(relPath string, data []byte) bool {
	if !IsEligiblePath(relPath) {
		return false
	}

	// Content binary check
	return !IsBinary(data)
}

// IsEligibleFile inspects the file at filePath to determine if it is eligible for processing.
func IsEligibleFile(filePath string) (bool, error) {
	if !IsEligiblePath(filePath) {
		return false, nil
	}

	info, err := os.Stat(filePath)
	if err != nil {
		if os.IsNotExist(err) {
			return false, nil
		}
		return false, err
	}

	if info.IsDir() || !info.Mode().IsRegular() {
		return false, nil
	}

	f, err := os.Open(filepath.Clean(filePath))
	if err != nil {
		return false, err
	}
	defer f.Close()

	buf := make([]byte, maxBinaryCheckBytes)
	n, err := f.Read(buf)
	if err != nil && !errors.Is(err, io.EOF) {
		return false, err
	}

	return IsEligible(filePath, buf[:n]), nil
}
